package com.volkanulutas.javabasicselif.lesson.week10.ifcondition;

public class W3L14_Condition_04_Fundamental_Operators {
    public static void main(String[] args) {
        int a = 5;
        int b = 3; // change it. b=9
        if (a == b) {
            System.out.println("a ve b eşittir.");
        } else {
            System.out.println("a ve b eşit değildir.");
        }
        if (a > b) {
            System.out.println("a, b'den büyüktür.");
        } else {
            System.out.println("a, b'den küçük veya eşittir.");
        }
    }
}
